"""rebuild_index.py — deterministic rebuild of ``index.md``.

Source: workshop S025 BL-04 (C1 index repair), architect sketch
[03 §B1](../workshop/03_architect.md), QM finding R3 / QK-12.

What the script does
====================
Walks ``wiki/**/*.md`` in the vault, parses frontmatter via
``agents.frontmatter.parse``, groups pages by their ``type`` field (VocabEntry
additionally by ``language`` into ``ES``/``EN`` buckets) and rewrites
``index.md`` deterministically. Section order and entry format are a contract
with [graph_reader._search_index_md](../agents/graph_reader.py) (phase 1 slug match).

What the script does NOT do
===========================
- **Write wiki content.** It only reads; there is no ``patch_frontmatter``
  write-back (brief S027, scope protection). If a migration wants to add a
  ``summary`` slot, that is a migration of its own.
- **LLM calls.** Summaries are derived deterministically from frontmatter
  fields (``word``/``name``/``story_score``/slug tokens). The one-off
  Sonnet/Haiku pass from the architect sketch §B1 is explicitly out of scope
  (brief S027, "no destructive requirement").
- **Run log.** Unlike migrations, no ``applied.json`` entry is written
  (brief F1: rebuild scripts are run on demand, not versioned).

Idempotency
===========
Identical wiki input -> byte-identical ``index.md``. If ``index.md`` is not
modified externally between two runs, the second run writes nothing
(``changed == False``).

Defensive behavior
==================
A ``YAMLError`` in a wiki file is not propagated: the path ends up in
``result["skipped"]`` with a reason and the run continues, the same way
``export_anki.py`` skips and reports.

Usage
=====
::

    python scripts/rebuild_index.py            # live rebuild
    python scripts/rebuild_index.py --dry-run  # show the plan without writing
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(REPO_ROOT / ".env")  # before agents.config (KOS_VAULT_ROOT)

from agents import frontmatter  # noqa: E402
from agents.config import VAULT_ROOT  # noqa: E402

WIKI_DIR = VAULT_ROOT / "wiki"
INDEX_PATH = VAULT_ROOT / "index.md"

INDEX_HEADER = (
    "# Index — LLM-Personal-Knowledge-OS\n"
    "<!-- generated by scripts/rebuild_index.py — do not edit -->\n\n"
    "---\n\n"
)

# (section title, bucket key, type filter, language filter)
# The order is a contract with graph_reader._normalize_type; changes need a
# matching edit there.
SECTION_SPECS: list[tuple[str, str, str, str | None]] = [
    ("PersonalFacts",       "PersonalFact",       "PersonalFact",   None),
    ("VocabEntries — ES",   "VocabEntry-es",      "VocabEntry",     "es"),
    ("VocabEntries — EN",   "VocabEntry-en",      "VocabEntry",     "en"),
    ("CulturalEntries",     "CulturalEntry",      "CulturalEntry",  None),
    ("LanguageBridges",     "LanguageBridge",     "LanguageBridge", None),
    ("Concepts",            "Concept",            "Concept",        None),
    ("StyleProfiles",       "StyleProfile",       "StyleProfile",   None),
    ("TopicPages",          "TopicPage",          "TopicPage",      None),
    ("Human-Owned (health)", "HumanOwned",        "HumanOwned",     None),
]

# Human-owned type family (SCHEMA §3.10, ENT-062): three types, one bucket.
HUMAN_OWNED_TYPES = ("HealthProtocol", "HealthReview", "DeepResearchPrompt")


def _bucket_key(fm: dict[str, Any]) -> str | None:
    """Map a frontmatter dict to a section bucket key. None = skip."""
    type_ = fm.get("type")
    if not type_:
        return None
    if type_ == "VocabEntry":
        lang = str(fm.get("language") or "").lower()
        if lang in ("es", "en"):
            return f"VocabEntry-{lang}"
        return None
    if type_ in HUMAN_OWNED_TYPES:
        return "HumanOwned"
    for _, key, t, _lang in SECTION_SPECS:
        if t == type_ and key == type_:
            return key
    return None


def _summary(slug: str, fm: dict[str, Any]) -> str:
    """Deterministic one-line summary from frontmatter fields.

    Precedence: the ``summary`` field (if a future migration adds it).
    Otherwise per type:
      - VocabEntry: the ``word`` field, else the slug.
      - LanguageBridge: ``Bridge: <word> (<from> ↔ <to>)`` from the slug pattern
        ``lb_<from>-<to>_<word>``, else the slug.
      - CulturalEntry: the ``name`` field, else the slug.
      - PersonalFact: ``slug (story_score: N)`` if ``story_score`` is set,
        else the slug.
      - TopicPage: ``<topic> (<domain>, N Quellen)`` from the ``topic``/``domain``/
        ``sources`` fields, else the slug ("Quellen" = sources; index content
        stays German).
      - Human-owned types (HUMAN_OWNED_TYPES): the ``title`` field, else the slug.
      - Otherwise: the slug.
    """
    if fm.get("summary"):
        return str(fm["summary"]).strip()
    type_ = fm.get("type")
    if type_ == "TopicPage":
        topic = str(fm.get("topic") or "").strip()
        domain = str(fm.get("domain") or "").strip()
        sources = fm.get("sources")
        n = len(sources) if isinstance(sources, list) else 0
        if topic and domain:
            return f"{topic} ({domain}, {n} Quellen)"
        return slug
    if type_ in HUMAN_OWNED_TYPES:
        title = str(fm.get("title") or "").strip()
        return title or slug
    if type_ == "VocabEntry":
        word = str(fm.get("word") or "").strip()
        return word or slug
    if type_ == "LanguageBridge":
        parts = slug.split("_", 2)
        if len(parts) == 3 and "-" in parts[1]:
            langs = parts[1].split("-")
            if len(langs) == 2:
                return f"Bridge: {parts[2]} ({langs[0]} ↔ {langs[1]})"
        return slug
    if type_ == "CulturalEntry":
        name = str(fm.get("name") or "").strip()
        return name or slug
    if type_ == "PersonalFact":
        score = fm.get("story_score")
        if score is not None:
            return f"{slug} (story_score: {score})"
        return slug
    return slug


def _render(buckets: dict[str, list[tuple[str, str]]]) -> str:
    """Render the bucket map to the final index.md text."""
    chunks = [INDEX_HEADER]
    for title, key, _type, _lang in SECTION_SPECS:
        entries = buckets.get(key, [])
        chunks.append(f"## {title} ({len(entries)})\n")
        for slug, summary in entries:
            chunks.append(f"- [[{slug}]] — {summary}\n")
        chunks.append("\n")
    return "".join(chunks).rstrip() + "\n"


def run(
    wiki_dir: Path = WIKI_DIR,
    index_path: Path = INDEX_PATH,
    *,
    dry_run: bool = False,
) -> dict[str, Any]:
    """Rebuild ``index.md`` from ``wiki_dir``.

    Returns
    -------
    dict with keys
      - ``rendered`` (str): the produced index.md text
      - ``changed`` (bool): True if disk content differs from rendered
      - ``entries`` (dict[str, list[tuple[str, str]]]):
        section-title -> sorted [(slug, summary), ...]
      - ``skipped`` (list[tuple[Path, str]]): files not bucketed, with reason
    """
    buckets: dict[str, list[tuple[str, str]]] = {key: [] for _, key, _, _ in SECTION_SPECS}
    skipped: list[tuple[Path, str]] = []
    seen: set[str] = set()

    if not wiki_dir.exists():
        rendered = _render(buckets)
        return {"rendered": rendered, "changed": False, "entries": {}, "skipped": skipped}

    for md in sorted(wiki_dir.rglob("*.md")):
        try:
            fm, _body = frontmatter.read(md)
        except yaml.YAMLError as exc:
            skipped.append((md, f"YAMLError: {exc.__class__.__name__}"))
            continue
        except OSError as exc:
            skipped.append((md, f"OSError: {exc}"))
            continue
        if not fm:
            skipped.append((md, "no frontmatter"))
            continue
        key = _bucket_key(fm)
        if key is None:
            skipped.append((md, f"unrecognized type={fm.get('type')!r}"))
            continue
        slug = md.stem
        if slug in seen:
            skipped.append((md, f"duplicate slug {slug!r}"))
            continue
        seen.add(slug)
        buckets[key].append((slug, _summary(slug, fm)))

    for key in buckets:
        buckets[key].sort(key=lambda pair: pair[0])

    rendered = _render(buckets)
    existing = index_path.read_text(encoding="utf-8") if index_path.exists() else ""
    changed = rendered != existing

    if changed and not dry_run:
        index_path.write_text(rendered, encoding="utf-8", newline="\n")

    entries = {title: buckets[key] for title, key, _t, _l in SECTION_SPECS}
    return {
        "rendered": rendered,
        "changed": changed,
        "entries": entries,
        "skipped": skipped,
    }


def _cli() -> int:
    p = argparse.ArgumentParser(
        description="Rebuild index.md deterministically from wiki/.",
    )
    p.add_argument("--dry-run", action="store_true",
                   help="Compute and report, but do not write index.md.")
    args = p.parse_args()

    result = run(dry_run=args.dry_run)
    total = sum(len(v) for v in result["entries"].values())
    label = "(dry-run) " if args.dry_run else ""
    print(f"{label}rebuild_index — {total} entries (vault: {VAULT_ROOT})")
    for section, items in result["entries"].items():
        print(f"  {section}: {len(items)}")
    if result["skipped"]:
        print(f"  skipped: {len(result['skipped'])}")
        for path, reason in result["skipped"]:
            try:
                rel = path.relative_to(VAULT_ROOT)
            except ValueError:
                rel = path
            print(f"    - {rel}: {reason}")
    if result["changed"]:
        verb = "would be rewritten" if args.dry_run else "rewritten"
        print(f"  index.md {verb}")
    else:
        print("  index.md unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(_cli())
